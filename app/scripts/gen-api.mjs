#!/usr/bin/env node
// Generates the shell's engine client types from the committed engine contracts (FR-API-2):
//   ../engine/openapi.json   -> src/shared/api/openapi.gen.ts  (openapi-typescript)
//   ../engine/ws-schema.json -> src/shared/api/ws.gen.ts       (json-schema-to-typescript)
// `--check` regenerates in memory and exits 1 if the committed files are stale. Never hand-edit the outputs.
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'
import { compile } from 'json-schema-to-typescript'

const here = path.dirname(fileURLToPath(import.meta.url))
const appRoot = path.resolve(here, '..')
const engineRoot = path.resolve(appRoot, '..', 'engine')
const outDir = path.join(appRoot, 'src', 'shared', 'api')

const OPENAPI_IN = path.join(engineRoot, 'openapi.json')
const WS_IN = path.join(engineRoot, 'ws-schema.json')
const OPENAPI_OUT = path.join(outDir, 'openapi.gen.ts')
const WS_OUT = path.join(outDir, 'ws.gen.ts')

const banner = (source) =>
  [
    '/* eslint-disable */',
    `// GENERATED by app/scripts/gen-api.mjs from engine/${source}. DO NOT EDIT.`,
    '// Regenerate with `bun run gen:api`; `bun run check:api` fails when this file is stale.',
    '',
  ].join('\n')

async function genOpenApi() {
  const spec = JSON.parse(await readFile(OPENAPI_IN, 'utf8'))
  const ast = await openapiTS(spec, {
    alphabetize: false,
    defaultNonNullable: true,
    exportType: false,
    rootTypes: false,
  })
  return `${banner('openapi.json')}\n${astToString(ast)}`
}

/** Every protocol message carries its `type` discriminator on the wire, so mark it required for narrowing. */
function requireDiscriminators(defs) {
  for (const def of Object.values(defs)) {
    const typeProp = def?.properties?.type
    if (typeProp && typeof typeProp.const === 'string') {
      def.required = Array.from(new Set([...(def.required ?? []), 'type']))
    }
  }
}

/**
 * Pydantic puts a `title` on every property; json-schema-to-typescript would turn each into a named alias
 * (`Ts1`, `Error`, ...). Keep titles only on the named models so property types are inlined.
 */
function stripPropertyTitles(node, isModel = true) {
  if (Array.isArray(node)) {
    node.forEach((n) => stripPropertyTitles(n, false))
    return
  }
  if (!node || typeof node !== 'object') return
  if (!isModel) delete node.title
  for (const [key, value] of Object.entries(node)) {
    if (key === 'properties' && value && typeof value === 'object') {
      for (const prop of Object.values(value)) stripPropertyTitles(prop, false)
    } else if (key !== '$defs' && typeof value === 'object') {
      stripPropertyTitles(value, false)
    }
  }
}

async function genWs() {
  const raw = JSON.parse(await readFile(WS_IN, 'utf8'))
  const clientDefs = structuredClone(raw.client.$defs ?? {})
  const serverDefs = structuredClone(raw.server.$defs ?? {})
  for (const name of Object.keys(clientDefs)) {
    if (name in serverDefs && JSON.stringify(clientDefs[name]) !== JSON.stringify(serverDefs[name])) {
      throw new Error(`ws-schema: client and server define different "${name}" models`)
    }
  }
  const $defs = { ...serverDefs, ...clientDefs }
  requireDiscriminators($defs)
  for (const def of Object.values($defs)) stripPropertyTitles(def)
  const fixRefs = (node) => node // refs are already "#/$defs/<Name>" in both halves
  const combined = {
    $schema: raw.$schema,
    title: 'WsProtocol',
    description: `${raw.title}. ${raw.binary_frames}.`,
    type: 'object',
    additionalProperties: false,
    properties: {
      client: { title: 'ClientMessage', oneOf: fixRefs(raw.client.oneOf) },
      server: { title: 'ServerMessage', oneOf: fixRefs(raw.server.oneOf) },
    },
    required: ['client', 'server'],
    $defs,
  }
  const ts = await compile(combined, 'WsProtocol', {
    bannerComment: '',
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: false,
    strictIndexSignatures: true,
    unknownAny: true,
    format: true,
    style: { singleQuote: true, semi: false, printWidth: 110 },
  })
  const protocol = Number(raw.protocol)
  if (!Number.isInteger(protocol)) throw new Error('ws-schema.json: missing integer "protocol"')
  return [
    banner('ws-schema.json'),
    `/** WebSocket protocol version announced by the engine in its \`hello\` message. */`,
    `export const WS_PROTOCOL = ${protocol} as const`,
    '',
    ts.trimEnd(),
    '',
  ].join('\n')
}

async function main() {
  const check = process.argv.includes('--check')
  const outputs = [
    [OPENAPI_OUT, await genOpenApi()],
    [WS_OUT, await genWs()],
  ]
  let stale = 0
  for (const [file, content] of outputs) {
    const rel = path.relative(appRoot, file)
    if (check) {
      let current = ''
      try {
        current = await readFile(file, 'utf8')
      } catch {
        // missing counts as stale
      }
      if (current !== content) {
        stale++
        console.error(`stale: ${rel} (run \`bun run gen:api\`)`)
      } else {
        console.log(`ok: ${rel}`)
      }
    } else {
      await writeFile(file, content)
      console.log(`wrote ${rel}`)
    }
  }
  if (stale) process.exit(1)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
